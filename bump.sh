#!/bin/bash
# 에셋 URL에 내용 해시를 붙인다. 커밋 전에 실행하세요.
#
#   assets/app.js?v=a1b2c3d4
#
# 왜 필요한가:
#   *.html 은 캐시되지 않지만 assets/* 는 엣지에 최대 4시간 남습니다.
#   그동안 방문자는 '새 HTML + 옛 JS' 를 받습니다. 실제로 이 조합 때문에
#   신청 폼이 예전 mailto 동작으로 돌아갔습니다.
#   파일 내용이 바뀌면 URL 이 바뀌므로 캐시가 자동으로 무효화됩니다.
#
# ── 왜 한 파일이 아니라 훑는가 (2026-08-28) ──────────────────────
#
# 예전에는 `index.html` 한 줄만 고쳤습니다. 페이지가 그것뿐이던 때는
# 맞았지만, 영어·스페인어·포르투갈어 랜딩이 생기면서 **세 페이지가
# 조용히 낡았습니다.** `assets/app.js` 를 고쳤는데 네 페이지가 전부 옛
# 해시를 가리키고 있었고, 한국어 페이지만 보면 멀쩡해 보였습니다.
#
# 그래서 목록을 적지 않고 **훑습니다.** 말을 하나 더 늘려도, 페이지를
# 하나 더 만들어도 저절로 걸립니다. 목록을 적어 두면 그 목록을 갱신하는
# 것을 잊는 날이 반드시 오고, 그날 낡는 쪽은 아무도 안 보는 페이지입니다.
#
# 방침·약관도 함께 훑습니다. 같은 `style.css` 를 쓰므로 같은 위험이
# 있습니다 — CSS 를 고친 날 그 두 페이지만 옛 것으로 그려집니다.
#
# ── 끝의 확인이 무엇을 하고 무엇을 못 하는가 ─────────────────────
#
# 예전에는 마지막에 `grep` 으로 찍어 보여주기만 했습니다. 눈으로 읽어야
# 알 수 있고, 한 줄이 빠져 있어도 초록불처럼 보입니다.
#
# **이 확인의 값어치는 「몇 개 페이지를 봤는가」라는 숫자입니다.** 말을
# 하나 더 늘렸는데 그 숫자가 안 늘면 그 자리에서 보입니다.
#
# **문지기 노릇은 크게 기대하지 마십시오.** 고치는 단계가 먼저 돌기
# 때문에, 여기까지 와서 어긋나 있으려면 위의 `perl` 이 닿지 못한
# 자리여야 합니다. 실제로 그런 경우를 만들어 보려 했지만 잘 안
# 만들어졌습니다. 그러니 **이 스크립트를 지켜주는 것은 확인이 아니라
# 「목록을 안 적고 훑는다」는 것**입니다. 확인은 그 위에 얹은 눈금입니다.
#
# 그래도 0 이 아닌 값으로 끝내게 둡니다 — 언젠가 물면 그때 값을 합니다.
set -euo pipefail
cd "$(dirname "$0")"

hash_of() { md5 -q "$1" 2>/dev/null || md5sum "$1" | cut -d' ' -f1; }

# 버전을 붙이는 것은 우리가 고치는 파일뿐입니다. og.png 는 공유 카드가
# 절대 주소로 가리키는 것이라 손대지 않습니다 — 주소가 바뀌면 이미
# 퍼진 카드가 깨집니다.
ASSETS=(style.css app.js)

# 훑을 파일. `.git` 만 빼고 전부입니다.
#
# `mapfile` 을 쓰지 않는 것은 맥의 /bin/bash 가 3.2 라 그것이 없기
# 때문입니다. 이 스크립트는 이 맥에서 돌게 되어 있으므로 3.2 에서
# 도는 방식으로 씁니다 — bash 4 를 요구하면 돌리려는 사람이 여기서
# 막히고, 막히면 안 돌리게 됩니다.
PAGES=()
while IFS= read -r P; do
  PAGES+=("$P")
done < <(find . -name '*.html' -not -path './.git/*' | sort)

if [ ${#PAGES[@]} -eq 0 ]; then
  echo "  ⚠ html 을 하나도 못 찾았습니다 — 이 스크립트를 site/ 에서 돌리셨습니까?"
  exit 1
fi

echo "훑는 파일 ${#PAGES[@]}개"
for F in "${ASSETS[@]}"; do
  H=$(hash_of "assets/$F" | cut -c1-8)
  for P in "${PAGES[@]}"; do
    # ?v=… 가 이미 있으면 갈아끼우고, 없으면 새로 붙인다.
    # `../assets/app.js` 도 같은 규칙에 걸립니다(경로 앞부분은 안 봅니다).
    perl -0pi -e "s{(assets/\Q$F\E)(\?v=[0-9a-f]+)?}{\$1?v=$H}g" "$P"
  done
  printf '  %-12s v=%s\n' "$F" "$H"
done

# ── 확인 ────────────────────────────────────────────────────────
echo
BAD=0
for F in "${ASSETS[@]}"; do
  WANT=$(hash_of "assets/$F" | cut -c1-8)
  SEEN=0
  for P in "${PAGES[@]}"; do
    # 이 페이지가 이 에셋을 참조하지 않으면 셀 것이 없습니다.
    grep -q "assets/$F" "$P" || continue
    GOT=$(grep -oE "assets/$F\?v=[0-9a-f]+" "$P" | sed 's/.*v=//' | sort -u)
    SEEN=$((SEEN + 1))
    if [ "$GOT" != "$WANT" ]; then
      echo "  ✗ $P — $F 가 [$GOT] 을 가리킵니다 (있어야 할 것 $WANT)"
      BAD=$((BAD + 1))
    fi
  done
  printf '  %-12s %s개 페이지가 v=%s 를 가리킵니다\n' "$F" "$SEEN" "$WANT"
done

echo
if [ "$BAD" -ne 0 ]; then
  echo "  ✗ $BAD 곳이 어긋납니다 — 커밋하지 마세요"
  exit 1
fi
echo "  ✓ 모든 페이지가 실제 파일과 같은 해시를 가리킵니다"
